"""Exporter tests on a SYNTHETIC model (no client data).

`testdata/synthetic_authoring.svg` is the file arena's Go test
(`apps/backend/internal/domain/seating/venue_gen_authoring_test.go`) feeds to `seating.ImportSVG`.
It is generated here; set VENUE_GEN_REGEN_FIXTURE=1 to rewrite it together with
`synthetic_authoring.expected.json` after an intentional change of the exporter.
"""
from __future__ import annotations

import copy
import json
import os
import tempfile
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

from arena_export import __main__ as cli
from arena_export.exporter import (
    DEFAULT_PROFILE_PATH,
    INK,
    SVG,
    build_authoring_svg,
    export_authoring_svg,
    load_profile,
    validate_profile,
)
from xlsx_seating_adapter.core import extract_workbook
from xlsx_seating_adapter.profiles import SYNTHETIC_PROFILE
from xlsx_seating_adapter.synthetic import build_synthetic_workbook

TESTDATA = Path(__file__).resolve().parents[1] / "testdata"
SVG_FIXTURE = TESTDATA / "synthetic_authoring.svg"
EXPECTED_FIXTURE = TESTDATA / "synthetic_authoring.expected.json"


def synthetic_model() -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        path = build_synthetic_workbook(Path(tmp) / "synthetic.xlsx")
        return extract_workbook(path, SYNTHETIC_PROFILE)


def expected_document(info: dict, profile: dict) -> dict:
    width, height = (float(v) for v in info["viewBox"].split()[2:])
    return {
        "_comment": "Generated by arena_export tests from a synthetic model. Read by the Go test venue_gen_authoring_test.go.",
        "canvas": {"width": width, "height": height},
        "category": {"name": profile["category"]["name"], "color": profile["category"]["color"].lower()},
        "seat_radius": info["seat_radius"],
        "seats": info["seats"],
    }


class ExporterTests(unittest.TestCase):
    def setUp(self):
        self.model = synthetic_model()
        self.profile = load_profile()

    def test_model_is_pass(self):
        self.assertEqual(self.model["validation"]["status"], "PASS")
        self.assertEqual(self.model["summary"]["seat_count"], 25)

    def test_structure_matches_the_import_contract(self):
        root = ET.fromstring(export_authoring_svg(self.model, self.profile))
        self.assertEqual(root.tag, f"{{{SVG}}}svg")
        self.assertEqual(root.get("viewBox"), "0 0 9 10")
        price = [g for g in root.findall(f"{{{SVG}}}g") if g.get("id") == "PriceCategory"]
        self.assertEqual(len(price), 1)
        self.assertEqual(price[0].get(f"{{{INK}}}label"), "#PriceCategory")
        swatches = price[0].findall(f"{{{SVG}}}circle")
        self.assertEqual([c.get(f"{{{INK}}}label") for c in swatches], ["#PLACEHOLDER"])
        self.assertIn("fill:#00aaff", swatches[0].get("style"))
        self.assertTrue(any(g.get("id") == "Legend" for g in root.findall(f"{{{SVG}}}g")))
        rows = [g for g in root.findall(f"{{{SVG}}}g") if g.get("id", "").startswith("row-")]
        self.assertEqual(len(rows), 5)
        self.assertEqual({g.get(f"{{{INK}}}label") for g in rows}, {"#PARTERRE", "#BALCONY"})
        for group in rows:
            self.assertIsNotNone(group.find(f"{{{SVG}}}title"))
        seats = [c for g in rows for c in g.findall(f"{{{SVG}}}circle")]
        self.assertEqual(len(seats), 25)
        self.assertEqual(len({c.get("id") for c in seats}), 25)
        for circle in seats:
            self.assertEqual(circle.get("r"), "0.32")
            self.assertIn("fill:#00aaff", circle.get("style"))
            self.assertTrue(circle.find(f"{{{SVG}}}title").text)

    def test_no_test_only_strings_and_no_sbt(self):
        svg = export_authoring_svg(self.model, self.profile)
        self.assertNotIn("TEST_ONLY", svg.upper())
        self.assertNotIn("sbt", svg)

    def test_profile_sets_category_canvas_radius(self):
        profile = copy.deepcopy(self.profile)
        profile["category"] = {"name": "Temp", "color": "#112233"}
        profile["canvas"] = {"width": 40, "height": 30}
        profile["seat_radius"] = 0.4
        root = ET.fromstring(export_authoring_svg(self.model, profile))
        self.assertEqual(root.get("viewBox"), "0 0 40 30")
        circles = [c for c in root.iter(f"{{{SVG}}}circle") if c.get("id", "").startswith("seat-")]
        self.assertEqual({c.get("r") for c in circles}, {"0.4"})
        self.assertTrue(all("fill:#112233" in c.get("style") for c in circles))
        label = root.find(f"{{{SVG}}}g/{{{SVG}}}circle").get(f"{{{INK}}}label")
        self.assertEqual(label, "#Temp")

    def test_arguments_override_profile(self):
        profile = copy.deepcopy(self.profile)
        profile["canvas"] = {"width": 40, "height": 30}
        profile["seat_radius"] = 0.4
        svg, info = build_authoring_svg(self.model, profile, canvas=(20, 15), radius=0.25)
        self.assertEqual(info["viewBox"], "0 0 20 15")
        self.assertEqual(info["seat_radius"], 0.25)
        self.assertIn('r="0.25"', svg)

    def test_canvas_limits(self):
        with self.assertRaises(ValueError):
            export_authoring_svg(self.model, self.profile, canvas=(2001, 100))
        with self.assertRaises(ValueError):
            export_authoring_svg(self.model, self.profile, canvas=(5, 5))  # does not enclose the seats

    def test_quarantine_and_bad_input_are_refused(self):
        quarantined = copy.deepcopy(self.model)
        quarantined["validation"]["status"] = "QUARANTINE"
        with self.assertRaises(ValueError):
            export_authoring_svg(quarantined, self.profile)
        reference = copy.deepcopy(self.model)
        reference["reference_svg_used"] = True
        with self.assertRaises(ValueError):
            export_authoring_svg(reference, self.profile)
        empty = copy.deepcopy(self.model)
        for row in empty["rows"]:
            row["seats"] = []
        with self.assertRaises(ValueError):
            export_authoring_svg(empty, self.profile)

    def test_profile_must_declare_non_commercial(self):
        bad = copy.deepcopy(self.profile)
        bad["commercial_data"] = True
        with self.assertRaises(ValueError):
            validate_profile(bad)
        bad = copy.deepcopy(self.profile)
        bad["category"]["color"] = "blue"
        with self.assertRaises(ValueError):
            validate_profile(bad)
        bad = copy.deepcopy(self.profile)
        del bad["commercial_data"]
        with self.assertRaises(ValueError):
            validate_profile(bad)

    def test_unnumbered_seats_stay_out_of_the_svg(self):
        model = copy.deepcopy(self.model)
        first = model["rows"][0]["seats"][0]
        first["number_status"] = "unknown"
        svg, info = build_authoring_svg(model, self.profile)
        self.assertEqual(info["seat_count"], 24)
        self.assertNotIn(first["seat_key"], svg)

    def test_cli_round_trip(self):
        with tempfile.TemporaryDirectory() as tmp:
            source, out = Path(tmp) / "m.json", Path(tmp) / "plan.svg"
            source.write_text(json.dumps(self.model), encoding="utf-8")
            self.assertEqual(cli.main(["--source", str(source), "--out", str(out)]), 0)
            self.assertEqual(out.read_text(encoding="utf-8"), export_authoring_svg(self.model, self.profile))

    def test_default_profile_is_bundled(self):
        self.assertTrue(DEFAULT_PROFILE_PATH.is_file())
        self.assertIs(self.profile["commercial_data"], False)

    def test_committed_fixture_is_current(self):
        svg, info = build_authoring_svg(self.model, self.profile)
        expected = expected_document(info, self.profile)
        if os.environ.get("VENUE_GEN_REGEN_FIXTURE") == "1":
            TESTDATA.mkdir(parents=True, exist_ok=True)
            SVG_FIXTURE.write_text(svg, encoding="utf-8", newline="\n")
            EXPECTED_FIXTURE.write_text(json.dumps(expected, indent=2) + "\n", encoding="utf-8", newline="\n")
        self.assertEqual(SVG_FIXTURE.read_text(encoding="utf-8"), svg, "regenerate with VENUE_GEN_REGEN_FIXTURE=1")
        self.assertEqual(json.loads(EXPECTED_FIXTURE.read_text(encoding="utf-8")), expected)


if __name__ == "__main__":
    unittest.main()
