"""Tests of the v2 authoring exporter on a SYNTHETIC model (no client data).

`testdata/v2_render.svg` and `testdata/v2_quarantine.svg` (with their `.expected.json`) are read by the
Go test `venue_gen_authoring_test.go`. Set VENUE_GEN_REGEN_FIXTURE=1 to rewrite them after an
intentional change of the exporter.
"""
from __future__ import annotations

import copy
import json
import os
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

from arena_export import build_authoring_svg_v2, load_profile
from arena_export.exporter import INK, SVG, build_authoring_svg
from hall_model import iter_seats, revalidate, to_v2
from xlsx_seating_adapter.core import extract_workbook
from xlsx_seating_adapter.profiles import SYNTHETIC_PROFILE
from xlsx_seating_adapter.synthetic import build_synthetic_workbook

TESTDATA = Path(__file__).resolve().parents[1] / "testdata"
SRC = {"index": 0, "kind": "xlsx", "sha256": "ab" * 32, "size_bytes": 10,
       "adapter": "xlsx_seating_adapter", "adapter_version": "0.1.0", "adapter_profile": "synthetic-v1"}


def synthetic_v1() -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        path = build_synthetic_workbook(Path(tmp) / "synthetic.xlsx")
        return extract_workbook(path, SYNTHETIC_PROFILE)


def synthetic_v2() -> dict:
    return to_v2(synthetic_v1(), source=SRC)


def rows_of(model: dict, section_label: str) -> list[dict]:
    return [r for s in model["sections"] if s["label"] == section_label for r in s["rows"]]


def render_model() -> dict:
    """PASS model with one unavailable seat (PARTERRE row 2, third seat)."""
    model = synthetic_v2()
    seat = rows_of(model, "PARTERRE")[1]["seats"][2]
    seat["status"] = "unavailable"
    seat["unavailable_reason"] = "blocked"
    return revalidate(model)


def quarantine_model() -> dict:
    """The render model with one row label and one seat number unknown."""
    model = render_model()
    balcony_row = rows_of(model, "BALCONY")[1]
    balcony_row["label"], balcony_row["label_status"] = None, "unknown"
    seat = rows_of(model, "PARTERRE")[2]["seats"][0]
    seat["number"], seat["number_status"] = None, "unknown"
    return revalidate(model)


def expected_document(info: dict, profile: dict) -> dict:
    width, height = (float(v) for v in info["viewBox"].split()[2:])
    return {
        "_comment": "Generated by arena_export tests from a synthetic v2 model. Read by the Go test venue_gen_authoring_test.go.",
        "canvas": {"width": width, "height": height},
        "category": {"name": profile["category"]["name"], "color": profile["category"]["color"].lower()},
        "seat_radius": info["seat_radius"],
        "marked": info["marked"],
        "omitted_seat_count": info["omitted_seat_count"],
        "unavailable_seats": info["unavailable_seats"],
        "seats": info["seats"],
    }


@pytest.fixture(scope="module")
def profile():
    return load_profile()


def decor_ids(root):
    return [e for e in root.iter() if (e.get("id") or "").startswith("decor")]


def test_parity_with_v1(profile):
    v1_svg, v1 = build_authoring_svg(synthetic_v1(), profile)
    v2_svg, v2 = build_authoring_svg_v2(synthetic_v2(), profile)
    assert v2_svg is not None
    as_tuples = lambda info: sorted((s["section"], s["row"], s["number"], s["x"], s["y"]) for s in info["seats"])
    assert as_tuples(v2) == as_tuples(v1)
    assert v2["seat_radius"] == v1["seat_radius"]
    assert v2["category"] == v1["category"]
    # v1 has no decor, so v2 may be a little wider (room for the row labels), never smaller.
    assert v1["viewBox"] == "0 0 200 224"
    v1_w, v1_h = (float(v) for v in v1["viewBox"].split()[2:])
    v2_w, v2_h = (float(v) for v in v2["viewBox"].split()[2:])
    assert v2_w >= v1_w and v2_h >= v1_h
    assert v2["scale"] == 24.0 and v2["offset"] == {"x": 0.0, "y": 0.0}
    assert v2["marked"] == "PASS"


def test_info_shape_and_marks(profile):
    svg, info = build_authoring_svg_v2(render_model(), profile)
    root = ET.fromstring(svg)
    assert root.get("data-validation-status") == "PASS"
    assert root.get("data-lane") == "exact"
    assert "PASS" in root.find(f"{{{SVG}}}desc").text
    assert info["seat_count"] == 24
    assert info["unavailable_seat_count"] == 1
    assert info["unavailable_seats"] == [{"section": "PARTERRE", "row": "2", "number": "3"}]
    assert info["omitted_seat_count"] == 0
    circles = [c for c in root.iter(f"{{{SVG}}}circle") if c.get("id", "").startswith("seat-")]
    assert len(circles) == 24
    assert len(decor_ids(root)) > 0
    assert not any((e.get(f"{{{INK}}}label") or "").startswith("#") for e in decor_ids(root))
    assert "TEST_ONLY" not in svg.upper() and "sbt" not in svg
    # The unavailable seat is a grey square and never a circle.
    squares = [e for e in root.iter(f"{{{SVG}}}rect") if e.get("id", "").startswith("decor-unavailable")]
    assert len(squares) == 1


def test_quarantine_marks_and_omits(profile):
    model = quarantine_model()
    assert model["validation"]["status"] == "QUARANTINE"
    svg, info = build_authoring_svg_v2(model, profile)
    root = ET.fromstring(svg)
    assert root.get("data-validation-status") == "QUARANTINE"
    assert "QUARANTINE" in root.find(f"{{{SVG}}}desc").text
    assert info["marked"] == "QUARANTINE"
    # One BALCONY row has no label (4 seats) and one PARTERRE seat has no number.
    assert info["omitted_seat_count"] == 5
    assert info["seat_count"] == 19


def test_schematic_lane_is_marked_schematic(profile):
    model = synthetic_v2()
    model["lane"] = "schematic"
    model["confirmed"] = False
    model = revalidate(model)
    svg, info = build_authoring_svg_v2(model, profile)
    assert info["marked"] == "SCHEMATIC"
    assert ET.fromstring(svg).get("data-lane") == "schematic"
    model["confirmed"] = True
    model = revalidate(model)
    assert model["validation"]["status"] == "PASS"
    assert build_authoring_svg_v2(model, profile)[1]["marked"] == "PASS"


def test_no_identified_seats(profile):
    model = synthetic_v2()
    for _, _, seat in iter_seats(model):
        seat["number"], seat["number_status"] = None, "unknown"
    svg, info = build_authoring_svg_v2(revalidate(model), profile)
    assert svg is None
    assert info["reason"] == "no_identified_seats"
    assert info["seat_count"] == 0


def test_duplicate_identity_is_not_exported(profile):
    model = synthetic_v2()
    seats = rows_of(model, "PARTERRE")[0]["seats"]
    seats[1]["number"] = seats[0]["number"]
    _, info = build_authoring_svg_v2(revalidate(model), profile)
    assert info["seat_count"] == 23
    assert info["omitted_seat_count"] == 2


def test_stage_and_labels(profile):
    model = synthetic_v2()
    model["stage"] = {"side": "top", "confidence": 1.0}
    svg, info = build_authoring_svg_v2(model, profile, {"stage": "SCENA"})
    root = ET.fromstring(svg)
    stage_text = [e for e in root.iter(f"{{{SVG}}}text") if e.get("id") == "decor-stage-text"]
    assert [e.text for e in stage_text] == ["SCENA"]
    assert info["offset"]["y"] > 0  # the stage needs room above the seats
    default = ET.fromstring(build_authoring_svg_v2(model, profile)[0])
    assert [e.text for e in default.iter(f"{{{SVG}}}text") if e.get("id") == "decor-stage-text"] == ["STAGE"]
    none = ET.fromstring(build_authoring_svg_v2(synthetic_v2(), profile)[0])
    assert not [e for e in none.iter() if e.get("id") == "decor-stage"]
    row_labels = [e.text for e in root.iter(f"{{{SVG}}}text") if e.get("id", "").startswith("decor-row-label")]
    assert len(row_labels) == 10  # 5 rows, both ends
    titles = [e.text for e in root.iter(f"{{{SVG}}}text") if e.get("id", "").startswith("decor-section-title")]
    assert sorted(titles) == ["BALCONY", "PARTERRE"]


def test_large_hall_is_scaled_down(profile):
    model = synthetic_v2()
    for _, _, seat in iter_seats(model):
        seat["position"] = {"x": seat["position"]["x"] * 400, "y": seat["position"]["y"]}
    svg, info = build_authoring_svg_v2(model, profile)
    width, height = (float(v) for v in info["viewBox"].split()[2:])
    assert max(width, height) <= 2000
    assert info["scale"] < 24.0  # the step (1 model unit) is smaller than 24 user units
    assert info["seat_radius"] == pytest.approx(0.32 * info["scale"], rel=1e-3)
    assert ET.fromstring(svg).get("viewBox") == info["viewBox"]


def test_v1_exporter_is_unchanged(profile):
    """The v1 fixture stays byte-identical: the v2 exporter must not touch it."""
    svg, _ = build_authoring_svg(synthetic_v1(), profile)
    assert (TESTDATA / "synthetic_authoring.svg").read_text(encoding="utf-8") == svg


@pytest.mark.parametrize("name,maker", [("v2_render", render_model), ("v2_quarantine", quarantine_model)])
def test_committed_fixture_is_current(name, maker, profile):
    svg, info = build_authoring_svg_v2(maker(), profile)
    expected = expected_document(info, profile)
    svg_path, json_path = TESTDATA / f"{name}.svg", TESTDATA / f"{name}.expected.json"
    if os.environ.get("VENUE_GEN_REGEN_FIXTURE") == "1":
        TESTDATA.mkdir(parents=True, exist_ok=True)
        svg_path.write_text(svg, encoding="utf-8", newline="\n")
        json_path.write_text(json.dumps(expected, indent=2) + "\n", encoding="utf-8", newline="\n")
    assert svg_path.read_text(encoding="utf-8") == svg, "regenerate with VENUE_GEN_REGEN_FIXTURE=1"
    assert json.loads(json_path.read_text(encoding="utf-8")) == expected


def test_unlabelled_section_and_main_section_never_export_the_same_triple(profile):
    model = synthetic_v2()
    first = model["sections"][0]
    first["label"] = "Main"
    twin = copy.deepcopy(model["sections"][1])
    twin.update(id="s-twin", label=None, label_status="unknown")
    for row in twin["rows"]:
        row["id"] = "twin-" + row["id"]
        for seat in row["seats"]:
            seat["key"] = "twin-" + seat["key"]
    model["sections"].append(twin)
    twin_row, first_row = twin["rows"][0], first["rows"][0]
    twin_row["label"], twin_row["seats"][0]["number"] = first_row["label"], first_row["seats"][0]["number"]
    model = revalidate(model)
    svg, info = build_authoring_svg_v2(model, profile)
    triples = [(s["section"], s["row"], s["number"]) for s in info["seats"]]
    assert len(triples) == len(set(triples))
    assert ("Main", first_row["label"], first_row["seats"][0]["number"]) not in triples
    assert info["omitted_seat_count"] >= 2
    assert any("duplicate_identity" in i["codes"] for i in model["issues"])


def test_blank_identity_is_never_exported(profile):
    model = synthetic_v2()
    seats = [s for _, _, s in iter_seats(model)]
    seats[0]["number"] = "  "
    svg, info = build_authoring_svg_v2(revalidate(model), profile)
    assert info["omitted_seat_count"] == 1
    assert info["seat_count"] == len(seats) - 1
