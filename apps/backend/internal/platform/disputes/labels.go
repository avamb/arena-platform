package disputes

// labels.go — the words of the evidence PDFs. The files for the provider and
// the bank are always English (owner decision 2026-11-02); the full package
// for the organizer is also written in the organization's language when it
// is Russian or Spanish.

import "strings"

type labels map[string]string

func (l labels) get(k string) string {
	if v, ok := l[k]; ok {
		return v
	}
	if v, ok := labelSets["en"][k]; ok {
		return v
	}
	return k
}

func labelsFor(locale string) labels {
	l := strings.ToLower(strings.TrimSpace(locale))
	if i := strings.IndexAny(l, "-_"); i > 0 {
		l = l[:i]
	}
	if s, ok := labelSets[l]; ok {
		return s
	}
	return labelSets["en"]
}

// packageLocale is the language of the organizer's full package.
func packageLocale(orgLocale string) string {
	l := strings.ToLower(strings.TrimSpace(orgLocale))
	if i := strings.IndexAny(l, "-_"); i > 0 {
		l = l[:i]
	}
	if _, ok := labelSets[l]; ok {
		return l
	}
	return "en"
}

