#!/usr/bin/env node
// Renders the Traefik file-provider fragments of a site cutover (spec 63 section 18). One config file per site.
//
//   node ops/site-cutover/render.mjs ops/site-cutover/sites/<site>.json \
//        --site-url http://<site web container>:80 --wp-url http://<wp container>:80 --out <dir>
//
// Writes two files into <dir>:
//   <name>-site.yml      the route at T0: new site on its paths, WordPress on the paths that stay with it
//   <name>-rollback.yml  the route before T2: only the paths the new site keeps for a buyer (same router name)
// Copy the one you need to /etc/dokploy/traefik/dynamic/ under the file name <name>-site.yml: Traefik
// reloads once, and the rollback replaces the T0 file instead of adding a second one.
// Without --out the T0 fragment goes to stdout. Container addresses are never stored in the site config:
// they are passed on the command line, or read from the config only if the owner wrote them there.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

// A YAML double-quoted scalar takes the same escapes as a JSON string.
const q = (s) => JSON.stringify(String(s));

export function loadSite(file) {
  const cfg = JSON.parse(readFileSync(file, 'utf8'));
  for (const key of ['name', 'host', 'site_always_rule', 'wp_routes']) {
    if (cfg[key] === undefined || cfg[key] === null) throw new Error(`${file}: field "${key}" is required`);
  }
  if (!/^[a-z0-9-]+$/.test(cfg.name)) throw new Error(`${file}: name must contain only a-z, 0-9 and dash`);
  if (!Array.isArray(cfg.wp_routes)) throw new Error(`${file}: wp_routes must be an array`);
  return cfg;
}

function checkUrl(label, url) {
  if (!url) throw new Error(`${label} is required (--${label.replace('_', '-')} or the site config)`);
  if (!/^https?:\/\/[^\s/]+$/.test(url)) {
    throw new Error(`${label} must be a bare origin such as http://<container>:80, got "${url}"`);
  }
}

// renderTraefik returns the YAML text of one fragment. rollback=true keeps only the always-site router.
export function renderTraefik(cfg, { siteUrl, wpUrl, rollback = false }) {
  checkUrl('site_url', siteUrl);
  if (!rollback) checkUrl('wp_url', wpUrl);
  const n = cfg.name;
  const host = `Host(\`${cfg.host}\`)`;
  const resolver = cfg.cert_resolver ?? 'letsencrypt';

  const router = (name, priority, rule, service) => [
    `    ${name}:`,
    `      rule: ${q(rule)}`,
    `      priority: ${priority}`,
    `      service: ${service}`,
    '      entryPoints:',
    '        - websecure',
    '      tls:',
    `        certResolver: ${q(resolver)}`,
  ].join('\n');

  const service = (name, url) => [
    `    ${name}:`,
    '      loadBalancer:',
    '        servers:',
    `          - url: ${q(url)}`,
    '        passHostHeader: true',
  ].join('\n');

  const routers = [
    // 3000: paths the new site always owns, also in a rollback (a token in sessionStorage is invisible to the router).
    router(`${n}-site-always`, 3000, `${host} && (${cfg.site_always_rule})`, `${n}-site-svc`),
  ];
  const services = [service(`${n}-site-svc`, siteUrl)];

  if (!rollback) {
    // 2000: paths that stay on WordPress during the transition.
    for (const r of cfg.wp_routes) {
      if (!r.name || !r.rule) throw new Error(`${cfg.name}: every wp_routes item needs name and rule`);
      routers.push(router(`${n}-${r.name}`, r.priority ?? 2000, `${host} && (${r.rule})`, `${n}-wp-svc`));
    }
    // 1500: operator's assets, only with the WordPress login cookie.
    if (cfg.wp_cookie_assets) {
      const c = cfg.wp_cookie_assets;
      routers.push(router(
        `${n}-wp-operator-assets`,
        c.priority ?? 1500,
        `${host} && HeaderRegexp(\`Cookie\`, \`${c.cookie}\`) && (${c.rule})`,
        `${n}-wp-svc`,
      ));
    }
    // 1000: the rest of the host is the new site.
    routers.push(router(`${n}-site`, 1000, host, `${n}-site-svc`));
    services.push(service(`${n}-wp-svc`, wpUrl));
  }

  const header = [
    `# Generated by ops/site-cutover/render.mjs from sites/${n}.json. Do not edit by hand: change the config and render again.`,
    rollback
      ? '# ROLLBACK before T2: replaces the T0 file under the same name. Only the paths the new site keeps for buyers stay on it.'
      : '# T0 route. Copy to /etc/dokploy/traefik/dynamic/ as <name>-site.yml. Port 80 is not routed here.',
  ].join('\n');

  return `${header}\nhttp:\n  routers:\n${routers.join('\n\n')}\n  services:\n${services.join('\n')}\n`;
}

function main() {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      'site-url': { type: 'string' },
      'wp-url': { type: 'string' },
      out: { type: 'string' },
    },
  });
  const [file] = positionals;
  if (!file) {
    process.stderr.write('usage: render.mjs <sites/site.json> [--site-url URL] [--wp-url URL] [--out DIR]\n');
    process.exit(2);
  }
  let cfg; let t0; let rollback;
  try {
    cfg = loadSite(file);
    const siteUrl = values['site-url'] ?? cfg.site_url;
    const wpUrl = values['wp-url'] ?? cfg.wp_url;
    t0 = renderTraefik(cfg, { siteUrl, wpUrl });
    rollback = renderTraefik(cfg, { siteUrl, rollback: true });
  } catch (err) {
    process.stderr.write(`render: ${err.message}\n`);
    process.exit(1);
  }
  if (values.out) {
    mkdirSync(values.out, { recursive: true });
    writeFileSync(join(values.out, `${cfg.name}-site.yml`), t0);
    writeFileSync(join(values.out, `${cfg.name}-rollback.yml`), rollback);
    process.stdout.write(`wrote ${cfg.name}-site.yml and ${cfg.name}-rollback.yml to ${values.out}\n`);
  } else {
    process.stdout.write(t0);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
